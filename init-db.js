
const db = require("./database");

async function initializeDatabase() {
    try {

        // 1. Create destinations table
        await db.query(`
            CREATE TABLE IF NOT EXISTS destinations (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(150) NOT NULL,
                state VARCHAR(150) NOT NULL,
                description TEXT,
                image VARCHAR(255)
            )
        `);

        // 2. Create packages table
        await db.query(`
            CREATE TABLE IF NOT EXISTS packages (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                destination_id INTEGER NOT NULL,
                title VARCHAR(200) NOT NULL,
                price DECIMAL(10,2) NOT NULL,
                duration VARCHAR(100) NOT NULL,

                FOREIGN KEY (destination_id)
                REFERENCES destinations(id)
            )
        `);

        // 3. Create enquiries table
        await db.query(`
            CREATE TABLE IF NOT EXISTS enquiries (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(150) NOT NULL,
                email VARCHAR(255) NOT NULL,
                phone VARCHAR(20) NOT NULL,
                destination_id INTEGER NOT NULL,
                package_id INTEGER,
                travel_date DATE NOT NULL,
                travellers INTEGER NOT NULL,
                budget VARCHAR(100),
                duration VARCHAR(100),
                contact_method VARCHAR(50),
                message TEXT,

                status VARCHAR(20) DEFAULT 'Pending'
                    CHECK (status IN ('Pending', 'Contacted', 'Confirmed')),

                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                FOREIGN KEY (destination_id)
                REFERENCES destinations(id),

                FOREIGN KEY (package_id)
                REFERENCES packages(id)
            )
        `);

        // 4. Create admins table
        await db.query(`
            CREATE TABLE IF NOT EXISTS admins (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(100) NOT NULL UNIQUE,
                password_hash VARCHAR(255) NOT NULL
            )
        `);

        console.log("Database tables created successfully!");

        
        // 5. Insert sample destinations
        const destinations = [
            ["Manali", "Himachal Pradesh",
                "Beautiful mountain destination", "/images/manali.jpg"],

            ["Kerala", "Kerala",
                "Famous for backwaters and greenery", "/images/kerala.jpg"],

            ["Jaipur", "Rajasthan",
                "Known for forts and royal heritage", "/images/jaipur.jpg"],

            ["Goa", "Goa",
                "Popular for beaches and tourism", "/images/goa.jpg"]
        ];

        for (const destination of destinations) {

            // Check whether destination already exists
            const existing = await db.query(
                "SELECT id FROM destinations WHERE name = $1",
                [destination[0]]
            );

            // Insert only if it does not exist
            if (existing.rows.length === 0) {
                await db.query(`
                    INSERT INTO destinations
                    (name, state, description, image)
                    VALUES ($1, $2, $3, $4)
                `, destination);
            }
        }

        console.log("Sample destinations inserted!");

        // 6. Insert sample packages
        const packages = [
            ["Manali", "Manali Mountain Escape", 8999, "5 Days / 4 Nights"],
            ["Kerala", "Kerala Backwater Tour", 12999, "6 Days / 5 Nights"],
            ["Jaipur", "Royal Rajasthan Tour", 7499, "4 Days / 3 Nights"],
            ["Goa", "Goa Beach Holiday", 9499, "4 Days / 3 Nights"]
        ];

        for (const pkg of packages) {

            // Find the destination ID
            const destinationResult = await db.query(
                "SELECT id FROM destinations WHERE name = $1",
                [pkg[0]]
            );

            if (destinationResult.rows.length === 0) {
                throw new Error("Destination not found: " + pkg[0]);
            }

            const destinationId = destinationResult.rows[0].id;

            // Check whether package already exists
            const existingPackage = await db.query(
                "SELECT id FROM packages WHERE title = $1",
                [pkg[1]]
            );

            // Insert only if it does not exist
            if (existingPackage.rows.length === 0) {
                await db.query(`
                    INSERT INTO packages
                    (destination_id, title, price, duration)
                    VALUES ($1, $2, $3, $4)
                `, [
                    destinationId,
                    pkg[1],
                    pkg[2],
                    pkg[3]
                ]);
            }
        }

        console.log("Sample packages inserted!");
        console.log("Database initialization completed!");

    } catch (error) {
        console.error("Database initialization failed:", error.message);
        process.exitCode = 1;

    } finally {
        await db.end();
    }
}

initializeDatabase();
